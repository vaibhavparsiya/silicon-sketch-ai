export async function api(path, body) {
  const response=await fetch(path,body===undefined?{cache:'no-store'}:{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});
  const data=await response.json();
  if(!response.ok)throw Object.assign(Error(data.error||'Request failed.'),{status:response.status,fallback:data.fallback_available});
  return data;
}
async function encodeDesign(design){
  const stream=new Blob([JSON.stringify(design)]).stream().pipeThrough(new CompressionStream('gzip'));
  const bytes=new Uint8Array(await new Response(stream).arrayBuffer());
  if(bytes.length>12000)throw Error('Snapshot storage is unavailable and this design is too large for a portable link.');
  return btoa(String.fromCharCode(...bytes)).replaceAll('+','-').replaceAll('/','_').replace(/=+$/,'');
}
async function decodeDesign(value){
  if(!/^[A-Za-z0-9_-]{1,16000}$/.test(value))throw Error('Invalid snapshot link.');
  const bytes=Uint8Array.from(atob(value.replaceAll('-','+').replaceAll('_','/')),ch=>ch.charCodeAt(0));
  const reader=new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip')).getReader();
  const chunks=[];let length=0;
  for(;;){
    const part=await reader.read();if(part.done)break;
    length+=part.value.length;
    if(length>524288){await reader.cancel();throw Error('Snapshot exceeds the design limit.');}
    chunks.push(part.value);
  }
  return api('/api/validate',JSON.parse(await new Blob(chunks).text()));
}
export function shareTools(read,restore){
  const save=document.getElementById('save'),result=document.getElementById('shared');
  save.onclick=async()=>{
    save.disabled=true;result.textContent='Saving snapshot…';
    try {
      const design=read();
      const url=new URL(design.kind==='logic'?'/':design.kind==='universal_rtl'?'/rtl':'/sequence',location.origin);
      try{const {id}=await api('/api/designs',design);url.searchParams.set('design',id);}
      catch(e){if(e.status!==503)throw e;url.hash='snapshot='+await encodeDesign(design);}
      const link=document.createElement('a');link.href=url.href;link.textContent=link.href;result.replaceChildren(link);
    } catch(err){result.textContent=err.message;} finally{save.disabled=false;}
  };
  const id=new URLSearchParams(location.search).get('design');
  const encoded=new URLSearchParams(location.hash.slice(1)).get('snapshot');
  const pending=id?api('/api/designs/'+encodeURIComponent(id)):encoded?decodeDesign(encoded):null;
  if(pending)pending.then(restore).catch(err=>{result.textContent=err.message;});
}

export function labPrompt(mode,apply){
  const form=document.getElementById('lab-prompt'),input=document.getElementById('request');
  const status=document.getElementById('prompt-status');
  let revision=0;
  input.addEventListener('input',()=>{revision++;status.textContent='';});
  form.onsubmit=async event=>{
    event.preventDefault();
    const ticket=++revision,prompt=input.value.trim();
    status.textContent='Interpreting your design…';
    try{
      const design=await api('/api/interpret',{prompt,preferred_mode:mode,force_ai:event.submitter?.value==='ai'});
      if(ticket!==revision)return;
      apply(design,prompt);
      status.textContent=design.compiler_source==='deterministic'?'Loaded with the built-in compiler.':'Generated by '+design.compiler_source+'.';
    }catch(e){
      if(ticket===revision)status.textContent=e.fallback?'AI generation needs a provider key. Use Compile with the example above or the manual controls below.':e.message;
    }
  };
}
